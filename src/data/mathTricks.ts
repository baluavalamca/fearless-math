export function trickCatLabel(id: TrickCatId, lang: DictLang): string {
  const c = TRICK_CATS.find((x) => x.id === id);
  if (!c) return id;
  return (lang === "hi" ? c.hi : lang === "te" ? c.te : c.en) || c.en;
}

export type TrickExample = { problem: string; working: string; answer: string };

export type CalcInputKind = "one" | "two" | "list";

export type TrickContent = {
  name: string;
  sutra: string;
  rule: string;
  whenToUse: string;
  steps: string[];
  examples: TrickExample[];
  calcLabel: string;
  calcHint: string;
};

export type Trick = {
  id: string;
  cat: TrickCatId;
  calcInputs: CalcInputKind;
  en: TrickContent;
  hi: TrickContent;
  te: TrickContent;
};

export function trick(lang: DictLang, t: Trick): TrickContent {
  return (lang === "hi" ? t.hi : lang === "te" ? t.te : t.en) || t.en;
}

